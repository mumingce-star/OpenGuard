FIXTURE = Path(__file__).resolve().parents[1] / 'fixtures/task33/is-number-7.0.0'
TASK = Path(__file__).resolve().parents[3]
SHA = lambda b: hashlib.sha256(b).hexdigest()

def dump(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n')

def database_state(root):
    # Hash all logical table contents, not merely row counts; reads use mode=ro.
    state = {}
    for p in sorted(root.glob('*.db')):
        with closing(sqlite3.connect(p.as_uri()+'?mode=ro',uri=True)) as db:
            state[p.name] = SHA('\n'.join(db.iterdump()).encode())
    return state

def archive_control(root, case):
    source = root/'source'; shutil.copytree(FIXTURE, source)
    archive = source/'is-number-7.0.0-derived.zip'
    if case in ('spdx_conflict', 'missing_declaration'):
        with zipfile.ZipFile(archive) as z: files={n:z.read(n) for n in z.namelist()}
        package=json.loads(files['package.json'])
        if case=='spdx_conflict': package['license']='GPL-3.0-only'
        else: package.pop('license',None)
        files['package.json']=json.dumps(package).encode()
        with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED) as z:
            for name,raw in files.items(): z.writestr(name,raw)
    if case in ('unuploaded_notice','incomplete_notice'):
        raw=(source/'archive.tgz').read_bytes()
        with tarfile.open(fileobj=io.BytesIO(raw), mode='r:gz') as t:
            files=[(m.name,t.extractfile(m).read()) for m in t.getmembers()]
        buf=io.BytesIO()
        with tarfile.open(fileobj=buf,mode='w') as t:
            for name,content in [*files,('package/NOTICE',b'TEST_ONLY: Additional declaration requires review.\n')]:
                info=tarfile.TarInfo(name); info.size=len(content);t.addfile(info,io.BytesIO(content))
        expanded=buf.getvalue()
        if case=='incomplete_notice': expanded=gzip.decompress(raw)+expanded # hidden second Tar
        raw=gzip.compress(expanded,mtime=0); (source/'archive.tgz').write_bytes(raw)
        metadata=json.loads((source/'metadata.json').read_text())
        metadata['dist'].update(integrity='sha512-'+base64.b64encode(hashlib.sha512(raw).digest()).decode(),shasum=hashlib.sha1(raw).hexdigest())
        (source/'metadata.json').write_text(json.dumps(metadata))
        profile=json.loads((source/'profile.json').read_text());item=profile['packages'][0]
        item['tarball_sha256']=SHA(raw);item['metadata_sha256']=SHA((source/'metadata.json').read_bytes())
        (source/'profile.json').write_text(json.dumps(profile))
    return source,archive

