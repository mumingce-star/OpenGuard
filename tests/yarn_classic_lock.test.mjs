import { strict as assert } from 'node:assert';
import { test } from 'node:test';
import { parseYarnClassicLock } from '../backend/app/scanners/yarn_classic_lock.mjs';

const raw = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@scope/main@^1.0.0", "@scope/main@1.0.0":
  version "1.0.0"
  resolved "https://packages.example.test/main.tgz"
  integrity sha512-synthetic
  dependencies:
    helper "^2.0.0"

helper@^2.0.0:
  version "2.0.0"
  dependencies:
    "@scope/main" "1.0.0"

helper@^3.0.0:
  version "3.0.0"
`;
const parse = input => parseYarnClassicLock(Buffer.from(input));

test('Classic v1 preserves grouped descriptors, lock offsets, versions and cycle edges', () => {
  const result = parse(raw);
  assert.equal(result.status, 'complete');
  assert.deepEqual(result.nodes.map(n => n.version), ['1.0.0', '2.0.0', '3.0.0']);
  assert.equal(result.nodes[0].versionLocator, 'yarn.lock#L5');
  assert.deepEqual(result.edges.map(e => [e.from, e.to]), [['yarn:4', 'yarn:11'], ['yarn:11', 'yarn:4']]);
  assert.equal(JSON.stringify(result).includes('packages.example'), false);
});

test('missing descriptors, alias and exact version mismatch do not fabricate edges', () => {
  const result = parse(raw.replace('helper "^2.0.0"', 'helper "^4.0.0"').replace('version "1.0.0"', 'version "1.0.1"') +
    '\nalias@npm:helper@2.0.0:\n  version "2.0.0"\n');
  assert.deepEqual(new Set(result.gaps.map(g => g.code)), new Set(['ambiguous_or_alias_descriptor', 'dependency_unresolved', 'dependency_version_conflict']));
  assert.equal(result.edges.length, 0);
});

test('unsupported schema, duplicated fields and malformed structure fail closed', () => {
  assert.throws(() => parse(raw.replace('lockfile v1', 'lockfile v2')), /unsupported_yarn/);
  assert.throws(() => parse(raw.replace('  version "1.0.0"', '  version "1.0.0"\n  version "2.0.0"')), /duplicate/);
  assert.throws(() => parse(raw.replace('    helper', '     helper')), /structure/);
  assert.throws(() => parse('a'.repeat(2 * 1024 * 1024 + 1)), /limit/);
});
